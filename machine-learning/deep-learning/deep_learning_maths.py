def naive_add_matrix_and_vector(x, y):
    # x is a rank-2 Numpy tensor.
    assert len(x.shape) == 2
    assert len(y.shape) == 1

    assert x.shape[1] == y.shape[0]

    x = x.copy()

    for i in range(x.shape[0]):
        for j in range(x.shape[1]):
            x[i, j] += y[j]

