"""### Element wise operations"""

def naive_relu(x):
    assert len(x.shape) == 2

    x = x.copy()
    for i in range(x.shape[0]):
        for j in range(x.shape[1]):
            x[i, i] = max(x[i, j], 0)

    return x

def naive_add(x, y):
    assert len(x.shape) == 2
    assert x.shape == y.shape

    z = x.copy()
    for i in range(x.shape[0]):
        for j in range(x.shape[1]):
            z[i, j] = x[i, j] + y[i, j]

    return z

